"""Canonical Flexe profile naming migration. MIT.

Kept separate from general profile creation so fleet migrations can be
maintained without changing native Fab setup or project customization.
"""
from pathlib import Path
import hashlib
import os
import tempfile

GENERATED_LAUNCHER_MARKER = "# Generated by agon-dev-env setup_emulator.py."

def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()

def replace_symlink(link: Path, target: Path) -> None:
    if link.is_symlink():
        link.unlink()
    elif link.exists():
        raise SystemExit(f"Refusing to replace non-symlink path: {link}")
    link.parent.mkdir(parents=True, exist_ok=True)
    link.symlink_to(os.path.relpath(target, link.parent))


def _executable_launcher_text(launcher: Path, *, allow_legacy_delegate: bool = False) -> str:
    if launcher.is_symlink() or not launcher.is_file():
        raise SystemExit(f"Launcher must be a real generated regular file: {launcher}")
    try:
        text = launcher.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as error:
        raise SystemExit(f"Cannot read generated launcher {launcher}: {error}") from error
    legacy = text == '#!/bin/sh\ncd "$(dirname "$0")"\nexec ./fab-agon-emulator "$@"\n'
    if (not text.startswith("#!") or
            (GENERATED_LAUNCHER_MARKER not in text and not (allow_legacy_delegate and legacy))):
        raise SystemExit(f"Refusing non-generated launcher: {launcher}")
    if not os.access(launcher, os.X_OK):
        raise SystemExit(f"Generated launcher is not executable: {launcher}")
    return text


def _verify_raw_executable(raw: Path) -> None:
    if not raw.is_file():
        raise SystemExit(f"Raw runtime must resolve to a regular file: {raw}")
    if not os.access(raw, os.X_OK):
        raise SystemExit(f"Raw runtime target is not executable: {raw}")


def verify_profile_executables(launcher: Path, raw: Path) -> None:
    """Check generated entry-point shape and execute access without launching.

    Supported raw symlinks must resolve to an executable regular file. This is
    not hash, MOS/firmware, dependency or complete environment verification.
    """
    _executable_launcher_text(launcher)
    _verify_raw_executable(raw)


def name_flexe_profile(profile: Path) -> None:
    """Name a generated Flexe launcher and raw link explicitly, preserving guards.

    Call after profile customization and before recording deployment identities.
    Existing .runtime.sha256 entries must verify before they are renamed.
    This migration changes no runtime binary, firmware, media or startup content.
    """
    old = profile / "fab-agon-emulator"
    new = profile / "flexe-agon-emulator"
    raw_old = profile / "fab-agon-emulator.bin"
    raw_new = profile / "flexe-agon-emulator.bin"
    pin = profile / ".runtime.sha256"
    mains = []
    for launcher in (new, old):
        if not launcher.exists() and not launcher.is_symlink():
            continue
        text = _executable_launcher_text(launcher, allow_legacy_delegate=True)
        delegate = (len(text) < 400 and
                    ('exec ./fab-agon-emulator "$@"' in text or
                     'exec ./flexe-agon-emulator "$@"' in text))
        if not delegate:
            mains.append((launcher, text))
    if not mains:
        raise SystemExit(f"Missing generated launcher in {profile}")
    marker = profile / ".bespoke-vdp-profile"
    selected = marker.read_text().lower() if marker.is_file() else ""
    if "flexe" not in selected and not any("AGON_FLEXE_" in body for _, body in mains):
        raise SystemExit(f"Refusing to label a non-Flexe profile as Flexe: {profile}")
    texts = [text.replace("fab-agon-emulator.bin", "flexe-agon-emulator.bin")
             for _, text in mains]
    if any(text != texts[0] for text in texts):
        raise SystemExit(f"Conflicting generated launchers in {profile}")
    text = texts[0]
    # Validate every supplied raw entry BEFORE canonicalization or writes.
    for raw in (raw_old, raw_new):
        if raw.exists() or raw.is_symlink():
            _verify_raw_executable(raw)
    runtime = raw_new if raw_new.exists() else raw_old
    if not runtime.is_file():
        raise SystemExit(f"Missing Flexe runtime in {profile}")
    if raw_old.exists() and raw_new.exists() and sha256(raw_old) != sha256(raw_new):
        raise SystemExit(f"Conflicting Flexe runtimes in {profile}")
    if raw_new.is_symlink() and not raw_new.exists():
        raise SystemExit(f"Broken Flexe runtime link in {profile}")
    # Resolve before removing redundant aliases, including raw_new -> raw_old.
    target = runtime.resolve(strict=True)
    entries = {}
    rename = {old.name: new.name, raw_old.name: raw_new.name,
              str(old.absolute()): str(new.absolute()),
              str(raw_old.absolute()): str(raw_new.absolute())}
    wrapper_names = {new.name, str(new.absolute())}
    if pin.exists():
        for line in pin.read_text().splitlines():
            expected, name = line.split("  ", 1)
            if sha256(profile / name) != expected:
                raise SystemExit(f"Runtime identity mismatch before migration: {name}")
            renamed = rename.get(name, name)
            if renamed not in wrapper_names and renamed in entries and entries[renamed] != expected:
                raise SystemExit(f"Conflicting runtime pins: {renamed}")
            entries[renamed] = expected
    # An already canonical profile is unchanged. All validation precedes writes.
    if (not old.exists() and not old.is_symlink() and
            not raw_old.exists() and not raw_old.is_symlink() and
            not new.is_symlink() and new.read_text() == text):
        verify_profile_executables(new, raw_new)
        return
    if target == raw_old:
        raw_old.rename(raw_new)
    elif raw_new.is_symlink() or not raw_new.exists():
        replace_symlink(raw_new, target)
    elif sha256(raw_new) != sha256(target):
        raise SystemExit(f"Conflicting Flexe runtime in {profile}")
    # Replace the wrapper inode so a shell already reading the old file can
    # finish normally; never rewrite a running launcher's open file in place.
    fd, temporary = tempfile.mkstemp(prefix=".flexe-launcher-", dir=profile)
    with os.fdopen(fd, "w") as stream:
        stream.write(text)
    os.chmod(temporary, 0o755)
    os.replace(temporary, new)
    old.unlink(missing_ok=True)
    raw_old.unlink(missing_ok=True)
    if pin.exists():
        for name in wrapper_names & entries.keys():
            entries[name] = sha256(new)
        pin.write_text("".join(f"{digest}  {name}\n" for name, digest in entries.items()))

    verify_profile_executables(new, raw_new)
